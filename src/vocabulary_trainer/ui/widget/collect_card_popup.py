"""The Collect card (FR-2.1 through FR-2.11, FR-3.6, FR-3.7).

Mirrors ``mockup/widget-collect.html`` and ``widget-collect-filled.html``: a word
input, single-select part-of-speech chips, a collection dropdown with an inline
"+ New collection..." flow, an Auto/Manual meaning toggle, a lookup status line or
manual meaning/example fields depending on the toggle, and a Save button.

Three behaviours are worth stating because they are easy to get wrong:

* **Save is enabled the moment a word and a type exist**, regardless of lookup state.
  The whole point of FR-2.8 is that a slow dictionary cannot cost the user a capture.
* **Lookup completion arrives on a worker thread.** Touching widgets from there would
  be undefined behaviour in Qt, so the result is marshalled onto the UI thread via a
  signal before anything is rendered.
* **Switching to Manual cancels any in-flight lookup.** Otherwise a dictionary
  response could land after the user has already started typing their own
  definition and silently overwrite it (FR-2.11).
"""

