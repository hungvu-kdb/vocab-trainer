    def show_beside(self, anchor: tuple[int, int, int, int]) -> None:
        from PySide6.QtGui import QGuiApplication

        x, y, width, height = anchor
        screen = QGuiApplication.primaryScreen()
        if screen is not None:
            area = screen.availableGeometry()
            bounds = Rect(area.x(), area.y(), area.width(), area.height())
        else:  # pragma: no cover
            bounds = Rect(0, 0, 1920, 1080)

        self.adjustSize()
        placement = place_beside(
            Rect(x, y, width, height), self.width(), self.height(), bounds
        )
        self.move(placement.x, placement.y)
        self.show()
        self._word_input.setFocus()

    def keyPressEvent(self, event: QKeyEvent) -> None:
        """Escape discards the entry, matching the close affordance (E2-S1 branch 3a)."""
        if event.key() == Qt.Key.Key_Escape:
            self.close()
            return
        super().keyPressEvent(event)

    def closeEvent(self, event: object) -> None:
        """Abandon an in-flight lookup only if its entry was never saved.

        The distinction matters and was originally missing: this card closes
        immediately on every successful save, so cancelling unconditionally here
        also cancelled the enrichment patch ``save_word`` had just scheduled, and a
        word saved before its lookup resolved kept a blank meaning forever
        (FR-2.9). When the save (or the duplicate hand-off) has taken ownership of
        the lookup, it is left running so its result can still patch the row; only
        a genuinely discarded entry -- closed via the X or Escape without saving --
        cancels, so a late result cannot write a row the user abandoned.
        """
        if self._lookup is not None and not self._handed_off_lookup:
            self._lookup.cancel()
        self._lookup = None
        if self._on_closed is not None:
            self._on_closed()
        super().closeEvent(event)  # type: ignore[arg-type]
